import tempfile
import unittest
from pathlib import Path

import aws_cdk as cdk
from aws_cdk import aws_s3_assets as s3_assets

from nomad_constructs.lambda_asset import PYTHON_CACHE_EXCLUDES


class PythonLambdaAssetTest(unittest.TestCase):
    def test_python_cache_changes_do_not_change_lambda_asset_key(self):
        with tempfile.TemporaryDirectory() as temp_dir:
            root = Path(temp_dir)
            source = root / "function"
            cache = source / "package" / "__pycache__"
            cache.mkdir(parents=True)
            (source / "main.py").write_text("def handler(event, context): return {}\n")
            (cache / "module.cpython-314.pyc").write_bytes(b"first generated bytecode")
            (source / "module.pyc").write_bytes(b"first loose bytecode")
            (source / "module.pyo").write_bytes(b"first optimized bytecode")

            first_key = self.asset_key(root / "app-first", source)

            (cache / "module.cpython-314.pyc").write_bytes(b"changed generated bytecode")
            (source / "module.pyc").write_bytes(b"changed loose bytecode")
            (source / "module.pyo").write_bytes(b"changed optimized bytecode")
            second_key = self.asset_key(root / "app-second", source)

            self.assertEqual(first_key, second_key)

    @staticmethod
    def asset_key(outdir: Path, source: Path) -> str:
        app = cdk.App(outdir=str(outdir))
        stack = cdk.Stack(app, "AssetTestStack")
        asset = s3_assets.Asset(
            stack,
            "FunctionAsset",
            path=str(source),
            exclude=list(PYTHON_CACHE_EXCLUDES),
        )
        return asset.s3_object_key


if __name__ == "__main__":
    unittest.main()
